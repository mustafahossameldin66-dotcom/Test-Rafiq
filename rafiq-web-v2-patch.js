// Replace the plan math with human-first language and sane conversions.
function humanRateV2(n,unit){
  n=Number(n||0); if(!Number.isFinite(n)||n<=0)return '—';
  const eps=.0001;
  if(unit==='جزء'){
    if(Math.abs(n-1)<eps)return 'جزء واحد';
    if(Math.abs(n-.5)<eps)return 'نصف جزء';
    if(Math.abs(n-.25)<eps)return 'ربع جزء';
    if(Math.abs(n-.125)<eps)return 'ثمن جزء';
    const pages=n*20;
    if(pages>=.9 && pages<=2.1) return `${Math.round(pages)} صفحة`;
    return `${n.toFixed(2)} جزء`;
  }
  if(unit==='حزب'){
    if(Math.abs(n-1)<eps)return 'حزب واحد';
    if(Math.abs(n-.5)<eps)return 'نصف حزب';
    const pages=n*10;
    if(pages>=.9 && pages<=2.1)return `${Math.round(pages)} صفحة`;
    return `${n.toFixed(2)} حزب`;
  }
  if(unit==='ربع حزب'){
    if(Math.abs(n-1)<eps)return 'ربع حزب واحد';
    const pages=n*2.5;
    if(pages>=.9 && pages<=2.1)return `${Math.round(pages)} صفحة`;
    return `${n.toFixed(2)} ربع حزب`;
  }
  if(unit==='صفحة'){
    if(Math.abs(n-1)<eps)return 'صفحة واحدة';
    return `${n.toFixed(n%1?2:0)} صفحة`;
  }
  if(unit==='آيات'){
    if(Math.abs(n-1)<eps)return 'آية واحدة';
    return `${n.toFixed(n%1?1:0)} آية`;
  }
  return `${n.toFixed(2)} ${unit||''}`.trim();
}
window.humanRateV2=humanRateV2;

